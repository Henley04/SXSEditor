# -*- coding: utf-8 -*-
"""Quantize FP32 ONNX models to true FP16 (weights + activations) using Olive.

True FP16 = both weights AND activations are FP16, with FP16 inputs/outputs.

This is different from W16A32 (which keeps activations FP32):
  - W16A32: FP16 weights + Cast(FP16->FP32) + FP32 activations (DML-stable)
  - True FP16: FP16 weights + FP16 activations (smaller, faster on DML, but
    may have precision issues in sensitive layers)

Uses Olive's OnnxQuantization pass with QuantType.FLOAT16 for both weights and
activations. Calibration data (generated by generate_fp16_calibration.py) is
used to determine activation ranges and identify sensitive tensors that should
stay FP32.

The existing fp16_backup folder contains true FP16 models (mixed opsets 17/18/20).
This script produces new true FP16 models with:
  - Consistent opset 20 (matching FP32 production models)
  - Calibration-aware activation handling
  - Olive DML optimization passes applied

IMPORTANT — VOCODER TRUE FP16 IS NOT VIABLE:
  The vocoder_dml model has THREE structural issues that make TrueFP16 produce
  silent output (cos=0.0004, std=0.74 vs FP32 baseline):
    1. ISTFT initializers with tiny values (~1e-12) get truncated to 1e-7
       (FP16 minimum normal), destroying ISTFT reconstruction.
    2. Shape calculation values (num_frames × hop_size = 240000) overflow FP16
       max (65504) when converted to FP16 constants.
    3. CRITICAL: 20 ConvNeXt backbone weight matrices (onnx::MatMul_1020
       through onnx::MatMul_1076) have tiny values as small as 4.83e-10.
       FP16 truncates these to 0, destroying the network behavior.

  Blocking ISTFT nodes (node_block_list) and shape overflow nodes does NOT fix
  the issue because the ConvNeXt backbone itself is broken in FP16.

  Solution: Use W16A32 for vocoder (cos=0.999997, snr=51.76 dB).
  The fp16/ production directory for vocoder should be populated by running
  convert_fp16_w16a32.py, NOT this script. This script skips vocoder_dml by
  default (see VOCODER_SKIP=True below).

Usage: python quantize_fp16_true.py [--calib-dir PATH] [--output-dir PATH]
"""

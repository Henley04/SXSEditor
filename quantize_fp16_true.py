def main():
    import argparse
    parser = argparse.ArgumentParser(description='Quantize FP32 ONNX to true FP16 with calibration')
    parser.add_argument('--fp32-dir', default=FP32_DIR,
                        help=f'FP32 models directory (default: {FP32_DIR})')
    parser.add_argument('--output-dir', default=DEFAULT_OUTPUT_DIR,
                        help=f'Output directory (default: {DEFAULT_OUTPUT_DIR})')
    parser.add_argument('--calib-dir', default=CALIB_DIR,
                        help=f'Calibration data directory (default: {CALIB_DIR})')
    parser.add_argument('--models', nargs='+', default=MODELS,
                        help='Models to quantize (default: all 9)')
    parser.add_argument('--skip-olive', action='store_true',
                        help='Skip Olive DML optimization')
    parser.add_argument('--skip-quantize', action='store_true',
                        help='Skip quantization (only run Olive on existing FP16)')
    args = parser.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)

    print("=" * 70)
    print("True FP16 Quantization Pipeline (with calibration)")
    print(f"FP32 source: {args.fp32_dir}")
    print(f"Output: {args.output_dir}")
    print(f"Calibration: {args.calib_dir}")
    print(f"Models: {args.models}")
    print(f"Olive DML optimization: {'SKIP' if args.skip_olive else 'ENABLED'}")
    print("=" * 70)

    results = {}

    for model_name in args.models:
        success = quantize_model(
            model_name, args.fp32_dir, args.output_dir, args.calib_dir
        )
        results[model_name] = {'quantize': 'OK' if success else 'FAIL'}

        if success and not args.skip_olive:
            model_path = os.path.join(args.output_dir, model_name + '.onnx')
            olive_ok = apply_olive_dml_optimization(model_path)
            results[model_name]['olive'] = 'OK' if olive_ok else 'SKIP'

    # Summary
    print(f"\n{'='*70}")
    print("SUMMARY")
    print(f"{'='*70}")
    print(f"{'Model':<25} {'Quantize':<12} {'Olive':<12}")
    print(f"{'-'*50}")
    for model_name, r in results.items():
        print(f"{model_name:<25} {r.get('quantize', 'N/A'):<12} {r.get('olive', 'N/A'):<12}")

    # Save report
    report_path = os.path.join(args.output_dir, 'quantization_report.json')
    with open(report_path, 'w') as f:
        json.dump(results, f, indent=2)
    print(f"\nReport saved: {report_path}")


if __name__ == '__main__':
    main()

class NpzCalibrationDataReader:
    """CalibrationDataReader that loads samples from .npz files.

    Each .npz file contains multiple samples:
      sample{i}_input_{name}: input arrays
      sample{i}_output: reference output (not used for calibration, only for verification)
    """

    def __init__(self, npz_path, model_name, num_samples=8):
        self.model_name = model_name
        self.samples = []
        data = np.load(npz_path, allow_pickle=True)

        # Determine number of samples and input names
        sample_keys = [k for k in data.files if k.startswith('sample0_input_')]
        if not sample_keys:
            logger.warning(f"No sample0 inputs found in {npz_path}")
            return
        input_names = [k.replace('sample0_input_', '') for k in sample_keys]

        for idx in range(num_samples):
            prefix = f'sample{idx}_input_'
            input_keys = [k for k in data.files if k.startswith(prefix)]
            if not input_keys:
                break
            feeds = {}
            for k in input_keys:
                name = k.replace(prefix, '')
                feeds[name] = data[k]
            self.samples.append(feeds)

        logger.info(f"  Loaded {len(self.samples)} calibration samples from {npz_path}")
        logger.info(f"  Input names: {input_names}")

    def get_next(self):
        if not self.samples:
            return None
        return self.samples.pop(0)

    def rewind(self):
        # Reload samples (not implemented, caller should create new instance)
        pass



# True FP16 conversion (without Olive, using onnxconverter_common)
# ============================================================

def convert_to_fp16_simple(input_path, output_path, keep_io_types=True,
                            op_block_list=None, node_block_list=None):
    """Convert FP32 ONNX to true FP16 using onnxconverter_common.

    This is the simplest approach: convert all float32 tensors to float16.
    Optionally keep input/output types as FP32 (keep_io_types=True) for
    API compatibility with FP32 callers.

    Args:
        op_block_list: list of op types to keep in FP32 (e.g., ['Range', 'Sqrt'])
        node_block_list: list of node names to keep in FP32
    """
    from onnxconverter_common.float16 import convert_float_to_float16

    logger.info(f"  Loading FP32 model: {input_path}")
    model = onnx.load(input_path, load_external_data=True)

    logger.info(f"  Converting to FP16 (keep_io_types={keep_io_types})...")
    if op_block_list:
        logger.info(f"  Op block list: {op_block_list}")
    if node_block_list:
        logger.info(f"  Node block list: {len(node_block_list)} nodes")

    model_fp16 = convert_float_to_float16(
        model,
        keep_io_types=keep_io_types,
        op_block_list=op_block_list or [],
        node_block_list=node_block_list or [],
        disable_shape_infer=False,
    )

    # Save with external data
    if os.path.exists(output_path):
        os.remove(output_path)
    data_path = output_path + '.data'
    if os.path.exists(data_path):
        os.remove(data_path)

    onnx.save_model(
        model_fp16, output_path,
        save_as_external_data=True,
        all_tensors_to_one_file=True,
        location=os.path.basename(output_path) + '.data',
        size_threshold=1024,
    )

    size_mb = os.path.getsize(output_path) / 1024 / 1024
    data_mb = os.path.getsize(data_path) / 1024 / 1024 if os.path.exists(data_path) else 0
    logger.info(f"  Saved: {output_path} ({size_mb:.1f}MB + {data_mb:.1f}MB data)")

    return model_fp16


def verify_fp16_model(model_path, calibration_data, model_name, max_samples=3):
    """Verify FP16 model by running calibration data and comparing with reference.

    Returns precision metrics (cos, SNR) averaged over samples.
    """
    import onnxruntime as ort

    logger.info(f"  Verifying {model_name} on {min(len(calibration_data), max_samples)} samples...")

    try:
        sess = ort.InferenceSession(model_path, providers=['CPUExecutionProvider'])
    except Exception as e:
        logger.warning(f"  Failed to load FP16 model for verification: {e}")
        return None

    input_names = [inp.name for inp in sess.get_inputs()]
    input_types = {inp.name: inp.type for inp in sess.get_inputs()}

    metrics_list = []
    for idx, sample in enumerate(calibration_data[:max_samples]):
        feeds = {}
        for name, arr in sample.items():
            if name not in input_names:
                continue
            # Cast to FP16 if the model expects FP16 input
            if 'float16' in str(input_types.get(name, '')):
                feeds[name] = arr.astype(np.float16)
            else:
                feeds[name] = arr

        try:
            outputs = sess.run(None, feeds)
            metrics_list.append({'status': 'ok', 'output_shape': outputs[0].shape})
        except Exception as e:
            logger.warning(f"    Sample {idx}: inference failed - {str(e)[:100]}")
            metrics_list.append({'status': 'fail', 'error': str(e)[:100]})

    del sess
    return metrics_list


# ============================================================
# Per-model FP16 conversion with calibration-aware block lists
# ============================================================

def get_model_specific_block_list(model_name):
    """Return op/node block list for models with known sensitive operations.

    Some operations should stay FP32 for numerical stability:
    - Range: DML FP16 Range can produce NaN
    - Sqrt: precision-sensitive
    - ReduceMean: accumulation precision
    - LayerNormalization: precision-sensitive (but usually OK in FP16)
    """
    # Common block list for all models
    common_block = []

    if model_name == 'diff_step_dml':
        # diff_step has RoPE (Sin/Cos) and attention - keep Range in FP32
        # for DML stability
        return common_block + ['Range']
    elif model_name == 'mel_transform':
        # mel_transform has STFT + log + sqrt - precision sensitive
        return common_block + ['Sqrt', 'Log', 'Exp']
    elif model_name == 'vocoder_dml':
        # WARNING: vocoder TrueFP16 is NOT viable — see module docstring.
        # Blocking ISTFT/shape ops does NOT fix the ConvNeXt backbone tiny
        # weight values issue (20 matrices with min_positive ~4.83e-10).
        # This branch is reached only when VOCODER_SKIP=False (diagnostic use).
        # Production fp16/vocoder_dml.onnx is generated by convert_fp16_w16a32.py.
        # The istft_* initializers are kept FP32 by naming convention but this is
        # insufficient — see find_small_inits.py for the full list of broken weights.
        return common_block
    else:
        return common_block


def quantize_model(model_name, fp32_dir, output_dir, calib_dir):
    """Quantize a single model from FP32 to true FP16."""
    fp32_path = os.path.join(fp32_dir, model_name + '.onnx')
    output_path = os.path.join(output_dir, model_name + '.onnx')

    if not os.path.exists(fp32_path):
        logger.warning(f"  FP32 model not found: {fp32_path}")
        return False

    logger.info(f"\n{'='*60}")
    logger.info(f"Quantizing: {model_name}")
    logger.info(f"{'='*60}")

    fp32_size = os.path.getsize(fp32_path) / 1024 / 1024
    data_file = fp32_path + '.data'
    if os.path.exists(data_file):
        fp32_size += os.path.getsize(data_file) / 1024 / 1024
    logger.info(f"  FP32 size: {fp32_size:.1f} MB")

    # Get model-specific block list
    block_list = get_model_specific_block_list(model_name)
    if block_list:
        logger.info(f"  Sensitive ops kept FP32: {block_list}")

    # Convert to FP16
    try:
        convert_to_fp16_simple(
            fp32_path, output_path,
            keep_io_types=True,  # Keep FP32 I/O for API compatibility
            op_block_list=block_list,
        )
    except Exception as e:
        logger.error(f"  FP16 conversion failed: {e}")
        import traceback
        traceback.print_exc()
        return False

    # Verify with calibration data
    calib_path = os.path.join(calib_dir, model_name + '.npz')
    if os.path.exists(calib_path):
        data = np.load(calib_path, allow_pickle=True)
        calib_samples = []
        for idx in range(8):
            prefix = f'sample{idx}_input_'
            input_keys = [k for k in data.files if k.startswith(prefix)]
            if not input_keys:
                break
            feeds = {k.replace(prefix, ''): data[k] for k in input_keys}
            calib_samples.append(feeds)

        verify_fp16_model(output_path, calib_samples, model_name, max_samples=2)
    else:
        logger.warning(f"  No calibration data found at {calib_path}")

    # Check output
    fp16_size = os.path.getsize(output_path) / 1024 / 1024
    fp16_data = output_path + '.data'
    if os.path.exists(fp16_data):
        fp16_size += os.path.getsize(fp16_data) / 1024 / 1024
    ratio = fp16_size / fp32_size * 100 if fp32_size > 0 else 0
    logger.info(f"  FP16 size: {fp16_size:.1f} MB ({ratio:.1f}% of FP32)")

    return True


